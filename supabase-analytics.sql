-- STEP 14. The tick in Settings > Users & Roles.
--
-- Website Analytics is a new thing a role may be given, and phase 10
-- seeded the roles row before it existed. This adds the key to any role
-- that has no opinion about it yet, and to no other.
--
-- WHAT IT DEFAULTS TO, and why. The same answer that role already has
-- for Dashboard. Both are the storefront at a glance and neither
-- changes anything, so a role trusted with one is trusted with the
-- other — which gives Administrator the analytics and leaves Agent, who
-- only answers chats, exactly as they were. A role that has already
-- been given or refused it is left alone, so running this file again
-- never undoes a decision made in Settings.
