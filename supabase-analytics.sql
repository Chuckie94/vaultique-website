update public.site_settings s
   set data = (
     select jsonb_object_agg(
              role_key,
              case
                when role_def ? 'permissions'
                 and not (role_def->'permissions' ? 'analytics')
                then jsonb_set(role_def, '{permissions,analytics}',
                               coalesce(role_def->'permissions'->'dashboard', 'false'::jsonb))
                else role_def
              end)
       from jsonb_each(s.data) as roles(role_key, role_def))
 where s.key = 'roles'
   and jsonb_typeof(s.data) = 'object'
   and exists (
     select 1 from jsonb_each(s.data) as roles(role_key, role_def)
      where role_def ? 'permissions'
        and not (role_def->'permissions' ? 'analytics'));

